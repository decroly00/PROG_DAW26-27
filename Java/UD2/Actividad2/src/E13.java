public class E13 {
    public static void main(String[] args) {
        // 13. Realiza un programa que calcule y escriba la suma y el producto de los 10 primeros
        //números naturales.
        int suma = 0;
        for (int i=0; i<10; i++) {
            suma = suma + i;
            System.out.println(suma);
        }
    }
}
